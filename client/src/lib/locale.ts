export function localizeApiError(message: unknown, locale: Locale, fallback: string) {
  if (typeof message !== "string" || !message) return fallback;
  let raw = message;
  let payload: { code?: string; message?: string } | null = null;
  const jsonStart = message.indexOf("{");
  if (jsonStart >= 0) {
    try { payload = JSON.parse(message.slice(jsonStart)); } catch { /* retain the server fallback */ }
  }
  if (payload?.code && API_ERROR_CODE_TRANSLATIONS[payload.code]) return API_ERROR_CODE_TRANSLATIONS[payload.code][locale];
  const text = payload?.message || raw;
  if (locale === "en") return text || fallback;
  return API_ERROR_TRANSLATIONS[text] || fallback;
}

function readPathname() {
  return typeof window === "undefined" ? "/" : `${window.location.pathname}${window.location.search}`;
}

export function setLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  localStorage.setItem(LOCALE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new Event(LOCALE_EVENT));
}

const useIsomorphicLayoutEffect = typeof window !== "undefined" ? useLayoutEffect : useEffect;

type LocaleContextValue = {
  locale: Locale;
  copy: PortalCopy;
  publicCopy: PublicCopy;
  setLocale: (locale: Locale) => void;
  setUserLocale: (locale: Locale | null) => void;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [path, setPath] = useState(readPathname);
  const [storedLocale, setStoredLocale] = useState<Locale | null>(readStoredLocale);
  const [userLocale, setUserLocale] = useState<Locale | null>(null);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const notify = () => {
      setPath(readPathname());
      setStoredLocale(readStoredLocale());
    };
    const originalPushState = window.history.pushState;
    const originalReplaceState = window.history.replaceState;
    const onLocaleChange = () => notify();
    window.history.pushState = function (...args) {
      originalPushState.apply(this, args);
      notify();
    };
    window.history.replaceState = function (...args) {
      originalReplaceState.apply(this, args);
      notify();
    };
    window.addEventListener("popstate", notify);
    window.addEventListener(LOCALE_EVENT, onLocaleChange);
    return () => {
      window.history.pushState = originalPushState;
      window.history.replaceState = originalReplaceState;
      window.removeEventListener("popstate", notify);
      window.removeEventListener(LOCALE_EVENT, onLocaleChange);
    };
  }, []);

  const locale = useMemo(() => resolveLocale(path, userLocale, storedLocale, readBrowserLocale()), [path, storedLocale, userLocale]);

  useIsomorphicLayoutEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    copy: PORTAL_COPY[locale],
    publicCopy: PUBLIC_COPY[locale],
    setLocale: (nextLocale) => {
      setLocale(nextLocale);
      setStoredLocale(nextLocale);
      setUserLocale(nextLocale);
    },
    setUserLocale,
  }), [locale]);

  return createElement(LocaleContext.Provider, { value }, children);
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used within LocaleProvider");
  return context;
}