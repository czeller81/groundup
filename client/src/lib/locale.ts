function readStoredLocale(): Locale | null {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem(LOCALE_KEY);
  return stored === "es" || stored === "en" ? stored : null;
}

function readBrowserLocale(): Locale {
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("es")) return "es";
  return "en";
}

function routeLocale(pathname: string): Locale | null {
  if (/^\/es(?:\/|$)/.test(pathname)) return "es";
  if (/^\/portal\/(?:login|reset-password)(?:\?|\/|$)/.test(pathname) && new URLSearchParams(pathname.split("?")[1] || "").get("locale") === "en") return "en";
  if (/^\/portal(?:\/|$)/.test(pathname)) return null;
  return "en";
}

export function resolveLocale(pathname: string, userLocale?: Locale | null, storedLocale?: Locale | null, browserLocale: Locale = "en"): Locale {
  return routeLocale(pathname) ?? userLocale ?? storedLocale ?? browserLocale;
}

