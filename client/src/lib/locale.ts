export function localizeFormText(locale: Locale, slug: string | undefined, key: "title" | "description" | "field", value: string, fieldKey?: string) {
  if (locale !== "es" || !slug) return value;
  const translation = FORM_COPY[slug]?.es;
  if (!translation) return value;
  if (key === "title") return translation.title;
  if (key === "description") return translation.description;
  return translation.fields[fieldKey || ""] || value;
}

export function localizeFormOption(locale: Locale, slug: string | undefined, value: string) {
  if (locale !== "es" || !slug) return value;
  return FORM_COPY[slug]?.es?.options?.[value] || value;
}

export type { PortalCopy };

function readLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return localStorage.getItem(LOCALE_KEY) === "es" ? "es" : "en";
}

export function setLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  localStorage.setItem(LOCALE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new Event(LOCALE_EVENT));
}

export function useLocale() {
  const [locale, updateLocale] = useState<Locale>(readLocale);

  useEffect(() => {
    const handleChange = () => updateLocale(readLocale());
    window.addEventListener(LOCALE_EVENT, handleChange);
    return () => window.removeEventListener(LOCALE_EVENT, handleChange);
  }, []);

  const changeLocale = (nextLocale: Locale) => {
    setLocale(nextLocale);
    updateLocale(nextLocale);
  };

  return { locale, copy: PORTAL_COPY[locale], setLocale: changeLocale };
}